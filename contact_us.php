        document.addEventListener('DOMContentLoaded', function () {
            const themeToggleBtn = document.getElementById('theme-toggle');
            const menuToggle = document.getElementById('menu-toggle');
            const menuClose = document.getElementById('menu-close');
            const mobileMenu = document.getElementById('mobile-menu');

            function toggleTheme() {
                const isDark = document.documentElement.classList.contains('dark');
                const newTheme = isDark ? 'light' : 'dark';
                document.documentElement.className = newTheme;
                localStorage.setItem('theme', newTheme);
            }

            if (themeToggleBtn) themeToggleBtn.addEventListener('click', toggleTheme);

            if (menuToggle && mobileMenu) {
                menuToggle.addEventListener('click', () => {
                    mobileMenu.classList.add('open');
                    document.body.style.overflow = 'hidden';
                });
            }

            if (menuClose && mobileMenu) {
                menuClose.addEventListener('click', () => {
                    mobileMenu.classList.remove('open');
                    document.body.style.overflow = '';
                });
            }

            // Close mobile menu when clicking a link
            mobileMenu?.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
                mobileMenu.classList.remove('open');
                document.body.style.overflow = '';
            }));

            // Active link highlighting
            const current = window.location.pathname.split('/').pop();
            document.querySelectorAll('header nav a').forEach(a => {
                const href = a.getAttribute('href') || '';
                if (href.split('/').pop() === current) {
                    a.classList.add('text-primary', 'border-b-2', 'border-primary', 'pb-1', 'font-bold');
                }
            });
            mobileMenu?.querySelectorAll('a').forEach(a => {
                const href = a.getAttribute('href') || '';
                if (href.split('/').pop() === current) {
                    a.classList.add('text-primary', 'font-bold');
                }
            });

            // Intersection Observer for scroll animations
            const observerOptions = { threshold: 0.1, rootMargin: '0px 0px -50px 0px' };
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('animate-fade-in');
                        observer.unobserve(entry.target);
                    }
                });
            }, observerOptions);
            document.querySelectorAll('.animate-fade-in').forEach(el => observer.observe(el));
        });
